#!/usr/bin/env python3
"""Copy guidance/*.md into tests/guidance.snapshot.ts.

A mod's tests cannot read files from disk, so the tests that check what a boost
carries read the references from that snapshot. Run this after editing a reference:

    python3 tests/snapshot-guidance.py          write the snapshot
    python3 tests/snapshot-guidance.py --check  exit 1 if the snapshot is out of date
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
files = sorted((root / "guidance").glob("*.md"))
rows = ",\n".join(f"  {json.dumps(f.name)}: {json.dumps(f.read_text(encoding='utf-8'), ensure_ascii=False)}" for f in files)
text = (
    "// Generated by tests/snapshot-guidance.py from guidance/*.md. Do not edit: run the script again after editing a reference.\n"
    f"export const GUIDANCE: Record<string, string> = {{\n{rows},\n}}\n"
)
out = root / "tests" / "guidance.snapshot.ts"

if "--check" in sys.argv:
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        print("tests/guidance.snapshot.ts is out of date: run python3 tests/snapshot-guidance.py")
        sys.exit(1)
    print(f"snapshot matches guidance/ ({len(files)} files)")
else:
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(root)} from {len(files)} files")
